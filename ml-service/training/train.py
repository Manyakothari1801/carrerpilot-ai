"""Train, compare, evaluate, and persist the Career Guidance AI prototype model."""
from __future__ import annotations

import csv
import json
from collections import Counter
from pathlib import Path

import joblib
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, confusion_matrix, precision_recall_fscore_support
from sklearn.model_selection import StratifiedKFold, cross_validate, train_test_split
from sklearn.naive_bayes import MultinomialNB
from sklearn.pipeline import Pipeline
from app.features import feature_text

ROOT = Path(__file__).resolve().parents[1]
DATA = Path(__file__).parent / "data" / "career_profiles.csv"
MODEL_DIR = ROOT / "models"
MODEL_VERSION = "career-rec-synthetic-v1"
FEATURE_SCHEMA_VERSION = "profile-features-v1"
SEED = 497


def pipeline(classifier) -> Pipeline:
    return Pipeline([
        ("features", TfidfVectorizer(ngram_range=(1, 2), min_df=2, sublinear_tf=True)),
        ("classifier", classifier),
    ])


def main() -> None:
    with DATA.open(encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    x = [feature_text(row) for row in rows]
    y = [row["career"] for row in rows]
    x_train, x_test, y_train, y_test = train_test_split(x, y, test_size=.25, random_state=SEED, stratify=y)
    candidates = {
        "logistic_regression": pipeline(LogisticRegression(max_iter=2000, random_state=SEED)),
        "multinomial_naive_bayes": pipeline(MultinomialNB(alpha=.35)),
    }
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=SEED)
    comparison = {}
    for name, model in candidates.items():
        values = cross_validate(model, x_train, y_train, cv=cv, scoring={"accuracy": "accuracy", "macroPrecision": "precision_macro", "macroRecall": "recall_macro", "macroF1": "f1_macro"})
        comparison[name] = {
            "cvAccuracyMean": float(values["test_accuracy"].mean()),
            "cvMacroPrecisionMean": float(values["test_macroPrecision"].mean()),
            "cvMacroRecallMean": float(values["test_macroRecall"].mean()),
            "cvMacroF1Mean": float(values["test_macroF1"].mean()),
            "cvMacroF1Std": float(values["test_macroF1"].std()),
        }
    selected_name = max(comparison, key=lambda name: (comparison[name]["cvMacroF1Mean"], name == "logistic_regression"))
    model = candidates[selected_name].fit(x_train, y_train)
    predicted = model.predict(x_test)
    precision, recall, f1, _ = precision_recall_fscore_support(y_test, predicted, average="macro", zero_division=0)
    labels = sorted(set(y))
    metrics = {
        "dataset": {
            "provenance": "Explicitly synthetic/curated academic seed profiles generated by training/generate_curated_dataset.py; no real users or placement outcomes.",
            "size": len(rows), "classDistribution": dict(sorted(Counter(y).items())), "randomSeed": SEED,
            "holdoutFraction": .25,
        },
        "selection": {"criterion": "highest 5-fold training-split macro F1; ties prefer logistic regression as the discriminative baseline", "selected": selected_name, "candidates": comparison},
        "syntheticHoldoutMetrics": {
            "accuracy": float(accuracy_score(y_test, predicted)), "macroPrecision": float(precision),
            "macroRecall": float(recall), "macroF1": float(f1), "labels": labels,
            "confusionMatrix": confusion_matrix(y_test, predicted, labels=labels).tolist(),
        },
        "limitations": [
            "Metrics measure separation of authored synthetic archetypes, not real-world career outcomes or employability.",
            "The dataset is small and reflects the authors' selected roles and skills; demographic fairness is not established.",
            "Confidence values are model probabilities on this prototype feature space and are not guarantees of career success.",
        ],
    }
    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    joblib.dump({"pipeline": model, "modelVersion": MODEL_VERSION, "featureSchemaVersion": FEATURE_SCHEMA_VERSION}, MODEL_DIR / "career_model.joblib")
    (MODEL_DIR / "metrics.json").write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    print(json.dumps(metrics, indent=2))


if __name__ == "__main__":
    main()

